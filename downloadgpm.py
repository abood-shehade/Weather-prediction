import os
import requests
import urllib.parse

# Ensure output folder exists
os.makedirs("GPpics2", exist_ok=True)

# Load URLs
with open("urls.txt", "r") as file:
    urls = [line.strip() for line in file if line.strip()]

for url in urls:
    try:
        parsed_url = urllib.parse.urlparse(url)
        query_params = urllib.parse.parse_qs(parsed_url.query)
        filename = query_params.get("LABEL", [os.path.basename(parsed_url.path)])[0]
        filename = filename.replace("/", "_")  # Make sure it's safe for Windows
        save_path = os.path.join("GPpics2", filename)

        if os.path.exists(save_path):
            print(f"✔ Already downloaded: {filename}")
            continue

        print(f"⬇ Downloading: {filename}")

        with requests.get(url, stream=True, auth=requests.utils.get_netrc_auth(url)) as response:
            response.raise_for_status()
            with open(save_path, "wb") as f:
                for chunk in response.iter_content(chunk_size=8192):
                    f.write(chunk)

        print(f"✅ Finished: {filename}")

    except Exception as e:
        print(f"❌ Failed to download from URL:\n{url}\nReason: {e}")

print("🚀 All downloads attempted.")